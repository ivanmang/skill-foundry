#!/usr/bin/env python3
"""List/search skills, refresh the catalog and skills index.

Sources:
  - published: .claude/skills/*/SKILL.md   (live skills)
  - drafts:    hub/inbox/*/SKILL.md     (pending promotion)

Usage:
  ./harness skills                      # list all
  ./harness skills --inbox              # drafts only
  ./harness skills --search <q>         # filter by name/description/category substring
  ./harness skills --category <c>       # filter by exact category
  ./harness skills --entry              # entry points only
  ./harness skills --refresh            # rewrite hub/catalog.json + docs/SKILLS_INDEX.md
  ./harness skills --check              # exit 1 if catalog/index are stale (no writes)
  ./harness skills --json
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from collections import Counter

from skill_foundry.paths import ROOT as HARNESS  # noqa: E402
from skill_foundry.lib import validate_skills  # noqa: E402 — reuse its frontmatter parser

LIVE = HARNESS / ".claude" / "skills"
INBOX = HARNESS / "hub" / "inbox"
CATALOG = HARNESS / "hub" / "catalog.json"
INDEX = HARNESS / "docs" / "SKILLS_INDEX.md"

_TRUTHY = {"true", "yes", "1", "on"}


def _is_true(value: str) -> bool:
    return (value or "").strip().lower() in _TRUTHY


def collect() -> list[dict]:
    out: list[dict] = []
    for base, status in ((LIVE, "published"), (INBOX, "draft")):
        if not base.exists():
            continue
        for d in sorted(base.iterdir()):
            sm = d / "SKILL.md"
            if not d.is_dir() or not sm.exists():
                continue
            fm, _err = validate_skills.parse_frontmatter(sm.read_text(encoding="utf-8", errors="replace"))
            out.append({
                "name": fm.get("name") or d.name,
                "description": (fm.get("description") or "").strip(),
                "category": (fm.get("category") or "").strip(),
                "license": (fm.get("license") or "").strip(),
                "entry": _is_true(fm.get("entry") or ""),
                "stages": [s.strip() for s in (fm.get("stages") or "").split(",") if s.strip()],
                "origin": (fm.get("origin") or "").strip(),
                "owner": (fm.get("owner") or "").strip(),
                "maturity": (fm.get("maturity") or "ready").strip(),
                "status": status,
                "path": str(d.relative_to(HARNESS)),
            })
    return out


def _catalog_payload(skills: list[dict]) -> dict:
    return {
        "version": 1,
        "generated": _dt.datetime.now(_dt.timezone.utc).isoformat(),
        "skills": [
            {k: s[k] for k in ("name", "description", "category", "license", "entry", "stages", "origin", "owner", "maturity", "status")}
            for s in skills
        ],
    }


def _first_sentence(desc: str, limit: int = 160) -> str:
    if len(desc) <= limit:
        return desc
    for sep in (". ", "。 "):
        idx = desc.find(sep)
        if 0 < idx < limit:
            return desc[:idx] + sep[0]
    # No sentence boundary inside the limit: cut at a word boundary.
    cut = desc[:limit]
    space = cut.rfind(" ")
    return (cut[:space] if space > 0 else cut).rstrip() + "…"


def _build_index(skills: list[dict]) -> str:
    published = [s for s in skills if s["status"] == "published"]
    entries = [s for s in published if s["entry"]]
    by_cat: dict[str, list[dict]] = {}
    for s in published:
        by_cat.setdefault(s["category"] or "<none>", []).append(s)

    lines = [
        "# Skills Index",
        "",
        f"_Auto-generated by `./harness skills --refresh` · {len(published)} skills · {len(entries)} entry points_",
        "",
        "> Regenerate with `./harness skills --refresh`. To route a task: pick the "
        "entry point that matches the request, then follow its stages.",
        "",
        "> **Adding a skill?** See [CREATING_SKILLS.md](CREATING_SKILLS.md).",
        "",
        "## Entry points (start here)",
        "",
    ]
    if not entries:
        lines.append("_(none)_")
    else:
        for s in entries:
            cat = s["category"] or "<none>"
            owner = s.get("owner") or ""
            lines.append(f"### {s['name']}  ·  `{cat}`" + (f"  ·  {owner}" if owner else ""))
            lines.append(f"- {_first_sentence(s['description'])}")
            if s["stages"]:
                lines.append(f"- stages: {', '.join(s['stages'])}")
            lines.append("")

    lines += ["## Skills by category", ""]
    for cat in sorted(by_cat):
        lines.append(f"### {cat} ({len(by_cat[cat])})")
        lines.append("")
        for s in by_cat[cat]:
            mark = "◎ " if s["entry"] else "  "
            tag = f" · {s.get('owner')}" if s.get("owner") else ""
            if s.get("maturity") and s["maturity"] not in ("ready", ""):
                tag += f" · {s['maturity']}"
            lines.append(f"{mark}`{s['name']}`{tag} — {_first_sentence(s['description'], 120)}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _skill_filter(s: dict, q: str, category: str | None, entry_only: bool, origin: str | None = None, maturity: str | None = None, owner: str | None = None) -> bool:
    if category and s["category"] != category:
        return False
    if origin and s.get("origin") != origin:
        return False
    if owner and s.get("owner") != owner:
        return False
    if maturity and s.get("maturity") != maturity:
        return False
    if entry_only and not s["entry"]:
        return False
    if q:
        hay = " ".join([s["name"].lower(), s["description"].lower(), (s["category"] or "").lower()])
        if q.lower() not in hay:
            return False
    return True


def refresh() -> None:
    skills = collect()
    CATALOG.write_text(json.dumps(_catalog_payload(skills), indent=2) + "\n", encoding="utf-8")
    INDEX.write_text(_build_index(skills), encoding="utf-8")
    print(f"✓ refreshed — {len(skills)} skill(s) → {CATALOG.relative_to(HARNESS)} + {INDEX.relative_to(HARNESS)}")


def check() -> int:
    skills = collect()
    fresh_skills = _catalog_payload(skills)["skills"]
    index_text = _build_index(skills)
    stale = []
    # Compare only the skills array (the 'generated' timestamp drifts by design).
    try:
        disk = json.loads(CATALOG.read_text(encoding="utf-8"))
        if disk.get("skills") != fresh_skills:
            stale.append(str(CATALOG.relative_to(HARNESS)))
    except (OSError, ValueError):
        stale.append(str(CATALOG.relative_to(HARNESS)))
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index_text:
        stale.append(str(INDEX.relative_to(HARNESS)))
    if stale:
        print("✗ stale index (run ./harness skills --refresh): " + ", ".join(stale), file=sys.stderr)
        return 1
    print("✓ catalog + skills index up to date")
    return 0


def mine() -> int:
    """Show what each detected agent's user dir exposes vs the hub catalog."""
    from skill_foundry.lib import install_skills
    all_skills = collect()
    hub = {s["name"]: s for s in all_skills if s["status"] == "published"}
    owned = {n for n, s in hub.items() if (s.get("origin") or "") == "native"}

    print(f"agent visibility — hub has {len(hub)} skills ({len(owned)} owned / native)")
    print()
    visible: set[str] = set()
    for label, parent, hint in install_skills.AGENTS:
        names = install_skills.agent_skill_names(parent)
        visible |= set(names)
        harness = sorted(set(names) & set(hub))
        missing_owned = sorted(owned - set(names))
        d = parent / "skills"
        where = str(d) if d.exists() else f"{d} (not present)"
        print(f"  {label:<14} {where}")
        line = f"      sees {len(harness)}/{len(hub)} harness skills"
        if missing_owned:
            line += f"  — missing owned: {', '.join(missing_owned)}"
        print(line)
        if not harness and d.exists():
            print("      (no harness skills visible)")
    print()
    local_only = sorted(visible - set(hub))
    if local_only:
        print(f"  local-only skills (visible but not in the hub): {', '.join(local_only)}")
        print("      these live in an agent's user dir, not in this repo — declare them in")
        print("      config/externals.json if other skills reference them by name.")
        print()
    print("  install the owned skills:   ./harness skills --install --scope core")
    print("  install everything:         ./harness skills --install")
    return 0


def _page_skill_md(s: dict) -> None:
    from skill_foundry.paths import ROOT

    p = ROOT / s["path"] / "SKILL.md"
    if not p.exists():
        print("  (no SKILL.md)")
        return
    print("\n" + "─" * 76)
    print(p.read_text(encoding="utf-8", errors="replace").rstrip())
    print("─" * 76 + "\n")


def _skill_detail(s: dict) -> bool:
    """Show one skill's details + an action menu. Return False to quit the browser."""
    from skill_foundry.lib import ui

    print()
    print(f"  {s['name']}  ·  {s.get('category') or '<none>'}")
    meta = f"status: {s['status']}   origin: {s.get('origin') or '?'}   owner: {s.get('owner') or '?'}   maturity: {s.get('maturity') or 'ready'}"
    print(f"  {meta}")
    if s.get("entry"):
        print("  ★ entry point")
    print(f"  path: {s.get('path')}")
    print()
    print(f"  {s.get('description', '').strip()}")
    print()

    actions = [("📄 view SKILL.md", "view")]
    if s["status"] == "published":
        actions.append(("📦 install this skill", "install"))
    else:
        actions.append(("💾 propose promote (preview)", "propose"))
    actions.extend([("⟋ back", "back"), ("❌ quit", "quit")])

    while True:
        act = ui.select_menu("Action (↑/↓ · Enter · q = back)", actions)
        if act in (None, "back"):
            return True
        if act == "quit":
            return False
        if act == "view":
            _page_skill_md(s)
        elif act == "install":
            from skill_foundry.lib import install_skills
            install_skills.main(["--name", s["name"]])
            print()
        elif act == "propose":
            from skill_foundry.cli import promote_skill
            promote_skill.main([s["name"], "--propose"])
            print()


def _browse_interactive(skills: list[dict]) -> int:
    """Arrow-key browser: ↑/↓ to pick a skill, Enter for details + actions."""
    from skill_foundry.lib import ui

    published = [s for s in skills if s["status"] == "published"]
    drafts = [s for s in skills if s["status"] == "draft"]
    order = published + drafts
    if not order:
        print("no skills to browse")
        return 0

    title = ui.c(
        f"Browse skills ({len(published)} published · {len(drafts)} draft) — ↑/↓ select · Enter detail · q quit",
        ui.BOLD,
    )
    while True:
        labels = []
        for s in order:
            mark = "✓ " if s["status"] == "published" else "◷ draft "
            cat = s.get("category") or "<none>"
            owner = s.get("owner") or ""
            labels.append(
                (f"{mark}{s['name']:<28} {cat:<15} {_first_sentence(s['description'], 44)} · {owner}",
                 s["name"])
            )
        name = ui.select_menu(title, labels)
        if not name:
            return 0
        matches = [x for x in order if x["name"] == name]
        if not matches:
            continue
        s = matches[0]
        if not _skill_detail(s):
            return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="List/search skills, refresh catalog + index.")
    ap.add_argument("--search", default=None, help="Filter by name/description/category substring.")
    ap.add_argument("--category", default=None, help="Filter by exact category.")
    ap.add_argument("--origin", default=None, help="Filter by exact origin (native|cannbot).")
    ap.add_argument("--owner", default=None, help="Filter by exact owner (skill-foundry|cannbot|…).")
    ap.add_argument("--maturity", default=None, help="Filter by maturity (ready|draft|deprecated).")
    ap.add_argument("--scope", choices=["core", "all"], default=None,
                    help="Preset for --install/--uninstall ('core' = origin: native).")
    ap.add_argument("--entry", action="store_true", help="Entry points only.")
    ap.add_argument("--name", action="append", default=None,
                    help="Only this skill, by folder name (repeatable; --install/--uninstall only).")
    ap.add_argument("--inbox", action="store_true", help="Show drafts only.")
    ap.add_argument("--refresh", action="store_true", help="Rewrite hub/catalog.json + docs/SKILLS_INDEX.md.")
    ap.add_argument("--check", action="store_true", help="Fail if catalog/index are stale (no writes).")
    ap.add_argument("--install", action="store_true", help="Symlink skills into each detected agent's user dir.")
    ap.add_argument("--uninstall", action="store_true", help="Remove the harness skill symlinks.")
    ap.add_argument("--dry-run", action="store_true", help="With --install/--uninstall: show what would change (no writes).")
    ap.add_argument("--mine", action="store_true", help="Show what each detected agent can see vs the hub (discoverability check).")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    if args.install or args.uninstall:
        from skill_foundry.lib import install_skills
        argv = ["--uninstall"] if args.uninstall else []
        if args.dry_run:
            argv += ["--dry-run"]
        if args.scope:
            argv += ["--scope", args.scope]
        if args.origin:
            argv += ["--origin", args.origin]
        if args.owner:
            argv += ["--owner", args.owner]
        if args.maturity:
            argv += ["--maturity", args.maturity]
        if args.category:
            argv += ["--category", args.category]
        if args.entry:
            argv += ["--entry"]
        if args.name:
            for _name in args.name:
                argv += ["--name", _name]
        return install_skills.main(argv)

    if args.mine:
        return mine()

    if args.refresh:
        refresh()
        return 0
    if args.check:
        return check()

    skills = collect()
    skills = [s for s in skills if _skill_filter(s, args.search or "", args.category, args.entry, args.origin, args.maturity, args.owner)]
    if args.inbox:
        skills = [s for s in skills if s["status"] == "draft"]

    if args.json:
        print(json.dumps({"skills": skills}, indent=2))
        return 0

    published = [s for s in skills if s["status"] == "published"]
    drafts = [s for s in skills if s["status"] == "draft"]
    filtered = bool(args.search or args.category or args.origin or args.owner
                    or args.maturity or args.entry)
    if sys.stdin.isatty() and not args.json and not args.inbox and not filtered:
        return _browse_interactive(skills)
    if not filtered and not args.inbox:
        entries = [s for s in published if s["entry"]]
        print(f"{len(published)} published · {len(drafts)} draft(s)")
        if entries:
            print("\n  Entry points (start here):")
            for s in entries:
                owner = f"  [{s['owner']}]" if s.get("owner") else ""
                print(f"    [✓] {s['name']:<28}{s['category']:<15}{_first_sentence(s['description'], 62)}{owner}")
        by_cat = Counter(s["category"] or "<none>" for s in published)
        print("\n  Skills by category:")
        cats = sorted(by_cat.items(), key=lambda kv: (-kv[1], kv[0]))
        colw = max((len(c) for c, _ in cats), default=0) + 1
        row = []
        for cat, n in cats:
            row.append(f"{cat:<{colw}}({n})")
            if len(row) == 3:
                print("    " + "  ".join(row))
                row = []
        if row:
            print("    " + "  ".join(row))
        if drafts:
            print("\n  Drafts (hub/inbox — pending promotion):")
            for s in drafts:
                print(f"    [◷] {s['name']:<28}{s['category'] or '<none>'}")
                print(f"         → ./harness promote-skill {s['name']} --pr")
        print("\n  Navigate:")
        print("    ./harness skills --category <c>  ·  --search <q>  ·  --owner <o>  ·  --origin <o>")
        print("    ./harness skills --entry         ·  --mine         ·  --inbox")
        return 0

    print(f"{len(published)} published · {len(drafts)} draft(s)")
    for s in skills:
        mark = "✓" if s["status"] == "published" else "◷"
        desc = _first_sentence(s["description"], 80)
        extra = " [entry]" if s["entry"] else ""
        owner = f"  [{s['owner']}]" if s.get("owner") else ""
        print(f"  [{mark}] {s['name']:<24}{s['category']:<14}{desc}{extra}{owner}")
        if s["status"] == "draft":
            print(f"       draft → ./harness promote-skill {s['name']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())