#!/usr/bin/env python3
"""List/search skills, refresh the catalog and skills index.

Sources:
  - published: .claude/skills/*/SKILL.md   (live skills)
  - drafts:    hub/inbox/*/SKILL.md     (pending promotion)

Usage:
  ./harness skills                      # list all
  ./harness skills --inbox              # drafts only
  ./harness skills --search <q>         # filter by name/description/category substring
  ./harness skills --category <c>       # filter by exact category
  ./harness skills --entry              # entry points only
  ./harness skills --refresh            # rewrite hub/catalog.json + docs/SKILLS_INDEX.md
  ./harness skills --check              # exit 1 if catalog/index are stale (no writes)
  ./harness skills --json
"""

from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys

from skill_foundry.paths import ROOT as HARNESS  # noqa: E402
from skill_foundry.lib import validate_skills  # noqa: E402 — reuse its frontmatter parser

LIVE = HARNESS / ".claude" / "skills"
INBOX = HARNESS / "hub" / "inbox"
CATALOG = HARNESS / "hub" / "catalog.json"
INDEX = HARNESS / "docs" / "SKILLS_INDEX.md"

_TRUTHY = {"true", "yes", "1", "on"}


def _is_true(value: str) -> bool:
    return (value or "").strip().lower() in _TRUTHY


def collect() -> list[dict]:
    out: list[dict] = []
    for base, status in ((LIVE, "published"), (INBOX, "draft")):
        if not base.exists():
            continue
        for d in sorted(base.iterdir()):
            sm = d / "SKILL.md"
            if not d.is_dir() or not sm.exists():
                continue
            fm, _err = validate_skills.parse_frontmatter(sm.read_text(encoding="utf-8", errors="replace"))
            out.append({
                "name": fm.get("name") or d.name,
                "description": (fm.get("description") or "").strip(),
                "category": (fm.get("category") or "").strip(),
                "license": (fm.get("license") or "").strip(),
                "entry": _is_true(fm.get("entry") or ""),
                "stages": [s.strip() for s in (fm.get("stages") or "").split(",") if s.strip()],
                "origin": (fm.get("origin") or "").strip(),
                "status": status,
                "path": str(d.relative_to(HARNESS)),
            })
    return out


def _catalog_payload(skills: list[dict]) -> dict:
    return {
        "version": 1,
        "generated": _dt.datetime.now(_dt.timezone.utc).isoformat(),
        "skills": [
            {k: s[k] for k in ("name", "description", "category", "license", "entry", "stages", "origin", "status")}
            for s in skills
        ],
    }


def _first_sentence(desc: str, limit: int = 160) -> str:
    if len(desc) <= limit:
        return desc
    for sep in (". ", "。 "):
        idx = desc.find(sep)
        if 0 < idx < limit:
            return desc[:idx] + sep[0]
    # No sentence boundary inside the limit: cut at a word boundary.
    cut = desc[:limit]
    space = cut.rfind(" ")
    return (cut[:space] if space > 0 else cut).rstrip() + "…"


def _build_index(skills: list[dict]) -> str:
    published = [s for s in skills if s["status"] == "published"]
    entries = [s for s in published if s["entry"]]
    by_cat: dict[str, list[dict]] = {}
    for s in published:
        by_cat.setdefault(s["category"] or "<none>", []).append(s)

    lines = [
        "# Skills Index",
        "",
        f"_Auto-generated by `./harness skills --refresh` · {len(published)} skills · {len(entries)} entry points_",
        "",
        "> Regenerate with `./harness skills --refresh`. To route a task: pick the "
        "entry point that matches the request, then follow its stages.",
        "",
        "## Entry points (start here)",
        "",
    ]
    if not entries:
        lines.append("_(none)_")
    else:
        for s in entries:
            cat = s["category"] or "<none>"
            origin = s.get("origin") or ""
            lines.append(f"### {s['name']}  ·  `{cat}`" + (f"  ·  {origin}" if origin else ""))
            lines.append(f"- {_first_sentence(s['description'])}")
            if s["stages"]:
                lines.append(f"- stages: {', '.join(s['stages'])}")
            lines.append("")

    lines += ["## Skills by category", ""]
    for cat in sorted(by_cat):
        lines.append(f"### {cat} ({len(by_cat[cat])})")
        lines.append("")
        for s in by_cat[cat]:
            mark = "◎ " if s["entry"] else "  "
            tag = f" · {s.get('origin')}" if s.get("origin") else ""
            lines.append(f"{mark}`{s['name']}`{tag} — {_first_sentence(s['description'], 120)}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _skill_filter(s: dict, q: str, category: str | None, entry_only: bool, origin: str | None = None) -> bool:
    if category and s["category"] != category:
        return False
    if origin and s.get("origin") != origin:
        return False
    if entry_only and not s["entry"]:
        return False
    if q:
        hay = " ".join([s["name"].lower(), s["description"].lower(), (s["category"] or "").lower()])
        if q.lower() not in hay:
            return False
    return True


def refresh() -> None:
    skills = collect()
    CATALOG.write_text(json.dumps(_catalog_payload(skills), indent=2) + "\n", encoding="utf-8")
    INDEX.write_text(_build_index(skills), encoding="utf-8")
    print(f"✓ refreshed — {len(skills)} skill(s) → {CATALOG.relative_to(HARNESS)} + {INDEX.relative_to(HARNESS)}")


def check() -> int:
    skills = collect()
    fresh_skills = _catalog_payload(skills)["skills"]
    index_text = _build_index(skills)
    stale = []
    # Compare only the skills array (the 'generated' timestamp drifts by design).
    try:
        disk = json.loads(CATALOG.read_text(encoding="utf-8"))
        if disk.get("skills") != fresh_skills:
            stale.append(str(CATALOG.relative_to(HARNESS)))
    except (OSError, ValueError):
        stale.append(str(CATALOG.relative_to(HARNESS)))
    if not INDEX.exists() or INDEX.read_text(encoding="utf-8") != index_text:
        stale.append(str(INDEX.relative_to(HARNESS)))
    if stale:
        print("✗ stale index (run ./harness skills --refresh): " + ", ".join(stale), file=sys.stderr)
        return 1
    print("✓ catalog + skills index up to date")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="List/search skills, refresh catalog + index.")
    ap.add_argument("--search", default=None, help="Filter by name/description/category substring.")
    ap.add_argument("--category", default=None, help="Filter by exact category.")
    ap.add_argument("--origin", default=None, help="Filter by exact origin (native|cannbot).")
    ap.add_argument("--entry", action="store_true", help="Entry points only.")
    ap.add_argument("--inbox", action="store_true", help="Show drafts only.")
    ap.add_argument("--refresh", action="store_true", help="Rewrite hub/catalog.json + docs/SKILLS_INDEX.md.")
    ap.add_argument("--check", action="store_true", help="Fail if catalog/index are stale (no writes).")
    ap.add_argument("--install", action="store_true", help="Symlink skills into each detected agent's user dir.")
    ap.add_argument("--uninstall", action="store_true", help="Remove the harness skill symlinks.")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    if args.install or args.uninstall:
        from skill_foundry.lib import install_skills
        return install_skills.main(["--uninstall"] if args.uninstall else [])

    if args.refresh:
        refresh()
        return 0
    if args.check:
        return check()

    skills = collect()
    skills = [s for s in skills if _skill_filter(s, args.search or "", args.category, args.entry, args.origin)]
    if args.inbox:
        skills = [s for s in skills if s["status"] == "draft"]

    if args.json:
        print(json.dumps({"skills": skills}, indent=2))
        return 0

    published = [s for s in skills if s["status"] == "published"]
    drafts = [s for s in skills if s["status"] == "draft"]
    print(f"{len(published)} published · {len(drafts)} draft(s)")
    for s in skills:
        mark = "✓" if s["status"] == "published" else "◷"
        desc = _first_sentence(s["description"], 80)
        extra = " [entry]" if s["entry"] else ""
        print(f"  [{mark}] {s['name']:<24}{s['category']:<14}{desc}{extra}")
        if s["status"] == "draft":
            print(f"       draft → ./harness promote-skill {s['name']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())