#!/usr/bin/env python3
"""Guided first-run setup: detect env, pick a target, write env.sh, pick a CANN.

Usage:
  ./harness onboarding
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

HARNESS = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from skill_foundry.cli import guide  # noqa: E402 — reuse banner / c / ask / ask_yesno / select_menu / choose_cann
from skill_foundry.lib import targets  # noqa: E402


def _have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def write_env_sh(entries: list[tuple[str, str]]) -> None:
    p = HARNESS / "env.sh"
    lines = ["# Machine-local environment (gitignored). Generated by ./harness onboarding."]
    lines += [f'export {k}="{v}"' for k, v in entries]
    p.write_text("\n".join(lines) + "\n", encoding="utf-8")


def pick_target() -> tuple[str, dict]:
    cfg = targets.load_config()
    names = targets.list_targets(cfg)
    if len(names) <= 1:
        name = names[0] if names else "pto-isa"
    else:
        opts = [(targets.target_label(targets.get_target(n, cfg) or {}), n) for n in names]
        name = guide.select_menu("Which target are you setting up?", opts) or names[0]
    return name, targets.get_target(name, cfg) or {}


def main(argv: list[str] | None = None) -> int:
    guide.banner("0 · Prerequisites")
    for name in ("python3", "git"):
        ok = _have(name)
        print(f"  {'✓' if ok else '✗'}  {name}")
    print()

    guide.banner("1 · Target")
    tname, t = pick_target()
    repo_env = t.get("repo_env") or "PTO_ISA_REPO"
    repo = targets.resolve_repo(t)
    print(f"  target: {t.get('label') or tname}  (env {repo_env} → {repo})")
    print()

    guide.banner("2 · CANN toolkit (ASCEND_HOME_PATH)")
    ascend = os.environ.get("ASCEND_HOME_PATH", "")
    if not ascend:
        chosen = guide.choose_cann()
        if chosen:
            ascend = chosen
            os.environ["ASCEND_HOME_PATH"] = chosen
            print(guide.c(f"  ✓  using {chosen}", guide.GREEN))
        else:
            print(guide.c("  → skipped — npu/costmodel/comm suites won't run until set.", guide.YELLOW))
    else:
        print(f"  ✓  already set: {ascend}")
    print()

    guide.banner(f"3 · {tname} checkout")
    pto_path = repo
    if pto_path.exists():
        print(f"  ✓  found: {pto_path}")
    else:
        url = t.get("repo_clone")
        clone = guide.ask_yesno(f"  {pto_path} not found — clone it now?", "y") if url else False
        if clone:
            subprocess.run(["git", "clone", url, str(pto_path)], check=False)
        if pto_path.exists():
            print(guide.c(f"  ✓  cloned: {pto_path}", guide.GREEN))
        else:
            print(guide.c(f"  → export {repo_env}=… and clone {tname} when ready.", guide.YELLOW))
    print()

    guide.banner("4 · Write env.sh")
    entries = [("ASCEND_HOME_PATH", ascend)]
    if repo_env.upper() != "ASCEND_HOME_PATH":
        entries.append((repo_env, str(pto_path)))
    if guide.ask_yesno("Write env.sh with these entries?", "y"):
        write_env_sh(entries)
        print(guide.c("  ✓  wrote env.sh (gitignored). source ./env.sh to use it.", guide.GREEN))
    else:
        print("  → skipped — remember: cp env.example.sh env.sh")
    print()

    guide.banner("5 · See it work (optional)")
    if guide.ask_yesno("Run the 2-minute sandboxed demo (no hardware needed)?", "y"):
        subprocess.run([str(HARNESS / "harness"), "demo"])
    print()

    print(guide.c("  ✓ Done. Next steps:", guide.GREEN))
    print("      source ./env.sh")
    print("      ./harness status            # one-glance dashboard (all targets)")
    print(f"      ./harness list --target {tname}   # what can run for {tname}")
    print(f"      ./harness run --target {tname} --all-suites --dry-run   # preview")
    print(f"      ./harness run --target {tname} --all-suites --quiet     # the real run")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())