#!/usr/bin/env python3
"""Guided first-run setup: detect env, write env.sh, pick a CANN, verify pto-isa.

Usage:
  ./harness onboarding
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

HARNESS = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HARNESS / "scripts"))
import guide  # noqa: E402 — reuse banner / c / ask / ask_yesno / select_menu / choose_cann


def _have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def write_env_sh(ascend: str, pto: str) -> None:
    p = HARNESS / "env.sh"
    p.write_text(
        "# Machine-local environment (gitignored). Generated by ./harness onboarding.\n"
        f"export ASCEND_HOME_PATH=\"{ascend}\"\n"
        f"export PTO_ISA_REPO=\"{pto}\"\n",
        encoding="utf-8",
    )


def main(argv: list[str] | None = None) -> int:
    guide.banner("0 · Prerequisites")
    for name in ("python3", "git"):
        ok = _have(name)
        print(f"  {'✓' if ok else '✗'}  {name}")
    print()

    guide.banner("1 · CANN toolkit (ASCEND_HOME_PATH)")
    ascend = os.environ.get("ASCEND_HOME_PATH", "")
    if not ascend:
        chosen = guide.choose_cann()
        if chosen:
            ascend = chosen
            os.environ["ASCEND_HOME_PATH"] = chosen
            print(guide.c(f"  ✓  using {chosen}", guide.GREEN))
        else:
            print(guide.c("  → skipped — npu/costmodel/comm suites won't run until set.", guide.YELLOW))
    else:
        print(f"  ✓  already set: {ascend}")
    print()

    guide.banner("2 · pto-isa checkout")
    pto = os.environ.get("PTO_ISA_REPO") or str(Path("~/pto-isa").expanduser())
    pto_path = Path(pto).expanduser()
    if pto_path.exists():
        print(f"  ✓  found: {pto_path}")
    else:
        clone = guide.ask_yesno(f"  {pto_path} not found — clone it now?", "y")
        if clone:
            subprocess.run(["git", "clone", "git@gitcode.com:ivanmang/pto-isa.git", str(pto_path)], check=False)
        if pto_path.exists():
            print(guide.c(f"  ✓  cloned: {pto_path}", guide.GREEN))
        else:
            print(guide.c(f"  → export PTO_ISA_REPO=… and clone pto-isa when ready.", guide.YELLOW))
    print()

    guide.banner("3 · Write env.sh")
    if guide.ask_yesno(f"Write env.sh with ASCEND_HOME_PATH={ascend or '(unset)'} and PTO_ISA_REPO={pto}?", "y"):
        write_env_sh(ascend, pto)
        print(guide.c("  ✓  wrote env.sh (gitignored). source ./env.sh to use it.", guide.GREEN))
    else:
        print("  → skipped — remember: cp env.example.sh env.sh")
    print()

    guide.banner("4 · See it work (optional)")
    if guide.ask_yesno("Run the 2-minute sandboxed demo (no hardware needed)?", "y"):
        subprocess.run([str(HARNESS / "harness"), "demo"])
    print()

    print(guide.c("  ✓ Done. Next steps:", guide.GREEN))
    print("      source ./env.sh")
    print("      ./harness status       # one-glance dashboard")
    print("      ./harness list         # what can run here")
    print("      ./harness run --all-suites --dry-run   # preview before the real run")
    print("      ./harness run --all-suites --quiet     # the real run")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())